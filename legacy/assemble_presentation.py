def main():
    # Read config to get brand name
    load_dotenv()
    config = configparser.ConfigParser()
    config.read('config.ini')
    brand_name = config.get('Crawler', 'search_terms')
    safe_brand_name = re.sub(r'\W+', '', brand_name.replace(' ', '_'))
    
    content_file = os.path.join("outputs", safe_brand_name, "presentation", "slider_buddy_content.txt")
    images_dir = os.path.join("outputs", safe_brand_name, "presentation", "images")
    
    # Outputs directly in the brand folder so they show up in Streamlit
    html_output = os.path.join("outputs", safe_brand_name, f"{safe_brand_name}_presentation.html")
    
    content_list = extract_content_with_gemini(content_file)
    
    if not content_list:
        print("No content to assemble.")
        return
    create_html(content_list, images_dir, html_output, safe_brand_name)

if __name__ == "__main__":
    main()
