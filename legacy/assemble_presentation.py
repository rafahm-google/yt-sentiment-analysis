import os
import json
import configparser
import re
from google import genai
from google.genai import types
from dotenv import load_dotenv


def extract_content_with_gemini(file_path):
    """Uses Gemini to extract structured content from the slider buddy file as JSON."""
    load_dotenv()
    client = genai.Client()
    
    if not os.path.exists(file_path):
        print(f"Error: File not found at {file_path}")
        return []
        
    with open(file_path, 'r', encoding='utf-8') as f:
        content = f.read()
        
    prompt = f"""
    Read the following slide content generated by 'Slider Buddy'.
    Extract the content for each slide.
    Return the result ONLY as a JSON list of objects, where each object has:
    'slide': integer (slide number)
    'headline': string
    'subtitle': string (optional)
    'bullets': list of strings (optional)
    'takeaway': string (optional)
    
    Content:
    {content}
    """
    
    print("Extracting structured content using Gemini...")
    response = client.models.generate_content(
        model='gemini-3-flash-preview',
        contents=prompt,
        config=types.GenerateContentConfig(
            response_mime_type="application/json",
        )
    )
    
    try:
        return json.loads(response.text)
    except Exception as e:
        print(f"Error parsing JSON from Gemini: {e}")
        print(response.text)
        return []



